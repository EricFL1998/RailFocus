def find_city(raw_city):
    if raw_city in city_facts:
        return raw_city, 'exact'

    if raw_city in SPECIAL_MAP:
        return SPECIAL_MAP[raw_city], 'special'

    for suffix in SUFFIXES:
        if raw_city.endswith(suffix):
            stripped = raw_city[:-len(suffix)]
            if stripped in city_facts:
                return stripped, f'stripped_{suffix}'

    for city in city_list:
        if raw_city.startswith(city):
            return city, 'prefix'

    return None, 'unmatched'

plan = {}
for raw_city in db_cities:
    target, method = find_city(raw_city)
    plan[raw_city] = {'target': target, 'method': method}

unmatched = [c for c, info in plan.items() if info['target'] is None]
exact = [c for c, info in plan.items() if info['method'] == 'exact']
special = [c for c, info in plan.items() if info['method'] == 'special']
strip = [c for c, info in plan.items() if info['method'].startswith('stripped')]
prefix = [c for c, info in plan.items() if info['method'] == 'prefix']

with open(plan_path, 'w', encoding='utf-8') as f:
    json.dump(plan, f, ensure_ascii=False, indent=2)

with open(summary_path, 'w', encoding='utf-8') as f:
    f.write(f'总城市数: {len(db_cities)}\n')
    f.write(f'完全匹配: {len(exact)}\n')
    f.write(f'特殊映射: {len(special)}\n')
    f.write(f'去后缀匹配: {len(strip)}\n')
    f.write(f'前缀匹配: {len(prefix)}\n')
    f.write(f'未匹配: {len(unmatched)}\n\n')

    f.write('特殊映射样例:\n')
    for c in special[:30]:
        f.write(f'  {c} -> {plan[c]["target"]}\n')

    f.write('\n去后缀匹配样例:\n')
    for c in strip[:30]:
        f.write(f'  {c} -> {plan[c]["target"]} ({plan[c]["method"]})\n')

    f.write('\n前缀匹配样例:\n')
    for c in prefix[:30]:
        f.write(f'  {c} -> {plan[c]["target"]}\n')

    f.write('\n未匹配城市:\n')
    for c in unmatched:
        f.write(f'  {c}\n')

print(f'完全匹配: {len(exact)}, 特殊映射: {len(special)}, 去后缀: {len(strip)}, 前缀: {len(prefix)}, 未匹配: {len(unmatched)}')
print(f'计划已写入: {plan_path}')
print(f'摘要已写入: {summary_path}')
